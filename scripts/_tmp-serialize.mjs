import { createServer } from 'vite';
import fs from 'node:fs';
globalThis.window = { setTimeout, clearTimeout, addEventListener() {} };
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const { serializeProject } = await server.ssrLoadModule('/src/typst/serialize.ts');
const { normalizeDoc } = await server.ssrLoadModule('/src/model/store.ts');
const raw = JSON.parse(fs.readFileSync(process.env.HOME + '/Desktop/杨文艺论文.iota.json', 'utf8'));
const doc = normalizeDoc(raw);
doc.localInfo = { cover: { title: '封面专用\n题目', author: '封面作者', date: '2026-09', subtitle: '副题只在封面' }, titlepage: { secrecy: '内部', title: '内封题目', titleEn: 'TITLEPAGE TITLE' } };
const p = serializeProject(doc);
const main = p.main;
for (const l of main.split('\n')) if (/^#(cover|titlepage)\(/.test(l)) console.log(l);
console.log('keywords:', main.match(/keywords[^\n]*/g)?.slice(0,2));
fs.writeFileSync(process.env.OUT, main);
await server.close();
